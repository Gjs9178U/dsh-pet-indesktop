/**
 * verify-build.mjs — is what is committed in lib/ the thing that will be installed,
 * and does it match src/?
 *
 * This package ships PREBUILT plain JS on purpose: `dsh plugin add
 * github:Gjs9178U/dsh-pet-indesktop` installs straight from the checkout, the
 * package declares no prepare/postinstall script, and that is what keeps the
 * install away from pnpm's allowBuilds gate. The price of that choice is that
 * lib/ can drift from src/ silently — nothing runs a compiler at install time to
 * notice. This file is what notices.
 *
 * It checks:
 *   1. every artifact `main` / `exports` / `files` promise actually exists
 *   2. the host half in lib/host/ is byte-identical to src/host/
 *   3. lib/index.js is the exact generated shim (not a copy of src/host/index.js,
 *      whose relative imports would point at files that are not there)
 *   4. lib/client.js is the generated banner plus src/client/index.js, byte for
 *      byte, and the CSS template literal agrees between the two copies once
 *      whitespace is normalised
 *   5. package.json declares everything an installable plugin must declare
 *      (dsh.bundle AND dsh.client, no lifecycle scripts, no @deepseek-ai/* peer)
 *
 * Usage: node scripts/verify-build.mjs
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')

const failures = []
const check = (ok, label) => {
  console.log(`  ${ok ? 'ok  ' : 'FAIL'} ${label}`)
  if (!ok) failures.push(label)
}

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8')
const fileAt = (rel) => join(ROOT, ...rel.split('/'))

console.log('artifacts:')
const REQUIRED = [
  'lib/index.js',
  'lib/host/index.js',
  'lib/client.js',
  'lib/types/index.d.ts',
  'lib/types/client/index.d.ts',
  'lib/assets/skins/deepsea.png',
  'lib/assets/skins/sakura.png',
  'lib/assets/skins/mint.png',
  'lib/assets/skins/twilight.png',
  'lib/assets/skins/caramel.png',
  'lib/.build-manifest.json',
  'cordis.patch.yml',
  'package.json',
  'README.md',
  'README.en.md',
  'CHANGELOG.md',
  'ARCHITECTURE.md',
  'LICENSE',
  'submission/data/plugins/Gjs9178U__dsh-pet-indesktop.yml',
]
for (const rel of REQUIRED) {
  const exists = existsSync(fileAt(rel))
  check(exists, `${rel}${exists ? ` (${String(statSync(fileAt(rel)).size)} bytes)` : ' is MISSING'}`)
}

console.log('\nhost half is in step with src:')
{
  const src = read('src/host/index.js')
  const built = read('lib/host/index.js')
  check(src === built, 'lib/host/index.js is byte-identical to src/host/index.js')
}

console.log('\nthe entry shim:')
{
  const shim = read('lib/index.js')
  // The shim re-exports the host module with `export *`, so every export the host
  // publishes (including the verifier helpers) is reachable from the package root
  // without a second list to keep in step. Asserted as a property, not a spelling:
  // the names below must actually resolve through it.
  check(
    /export \* from '\.\/host\/index\.js'/.test(shim),
    'lib/index.js re-exports the whole host module from ./host/index.js',
  )
  check(
    !/\bexport\s+(?:const|function)\s+(?:name|inject|apply)\b/.test(shim),
    'lib/index.js declares none of those itself — it is a re-export, not a copy',
  )
  check(
    !shim.includes('webServer.register'),
    'lib/index.js is a shim, not a copy of the host module (a copy would break its relative imports)',
  )
  // The property that matters: importing the entry gives the plugin's exports.
  const imported = await import(new URL('../lib/index.js', import.meta.url).href)
  for (const name of ['apply', 'name', 'inject', 'createStateStore', 'limits', 'clampPercent', 'validateStatePayload']) {
    check(imported[name] !== undefined, `the package entry exports ${name}`)
  }
  check(imported.name === 'dsh-pet-indesktop', `the entry's name is the plugin name (got ${String(imported.name)})`)
  check(
    Array.isArray(imported.inject) && imported.inject.length === 1 && imported.inject[0] === 'webServer',
    `the entry injects only webServer (got ${JSON.stringify(imported.inject)})`,
  )
}

console.log('\nthe client half, both copies:')
{
  const source = read('src/client/index.js')
  const bundle = read('lib/client.js')

  check(
    bundle.endsWith(source),
    'lib/client.js is src/client/index.js plus a banner — the source survives the copy byte for byte',
  )
  check(
    bundle.startsWith('/**\n * GENERATED FILE'),
    'lib/client.js opens with the generated banner',
  )
  check(
    bundle.includes('Generated by scripts/build.mjs') && /do not edit/i.test(bundle),
    'the banner names scripts/build.mjs as the generator and forbids hand edits',
  )
  check(
    !bundle.slice(0, bundle.indexOf('*/')).includes('`'),
    'the generated banner carries no backtick (it precedes the sheet, so a backtick there would break a line-based scan)',
  )
  check(
    /window\.__ModuleLoader__\.load\(\{/.test(bundle),
    'lib/client.js is in the window.__ModuleLoader__ wrapper format (a plain script, not an ESM module)',
  )
  check(
    !/^\s*export\s+(?:const|let|var|function|default|\{)/m.test(bundle),
    'lib/client.js contains no ESM export statement — the loader evaluates it as a script',
  )

  const sheetOf = (text) => {
    const match = /const CSS = `([\s\S]*?)`/.exec(text)
    return match === null ? null : match[1].replace(/\r/g, '').replace(/[ \t]+$/gm, '').trim()
  }
  const src = sheetOf(source)
  const lib = sheetOf(bundle)
  check(src !== null, 'src/client/index.js declares `const CSS = ...`')
  check(lib !== null, 'lib/client.js declares `const CSS = ...`')
  check(src !== null && src === lib, 'the two copies of the sheet are identical (whitespace aside)')
  if (src !== null) {
    // The pet's layer. 2147481000 is deliberate: above ordinary chrome, and 2000
    // BELOW the 2147483000 a full-frame intro overlay uses, so an intro covers the
    // pet instead of fighting it. ARCHITECTURE.md carries the reasoning.
    check(src.includes('z-index:2147481000'), 'the pet layer uses the agreed z-index (2147481000)')
    check(src.includes('position:fixed'), 'the pet layer is position:fixed')
    check(src.includes('pointer-events:none'), 'the pet layer lets clicks through except on the pet itself')
    check(src.includes('pointer-events:auto'), "...and the pet's own box takes them")
    check(src.includes('dpi-root'), 'the sheet styles the dpi- prefixed pet root')
    check(!/PROVISIONAL|placeholder/i.test(src), 'the sheet describes the pet itself, not a stand-in')
    check(
      /prefers-reduced-motion:\s*reduce/.test(src) && /animation:none/.test(src),
      'reduced motion collapses to a still frame rather than a slower animation',
    )
    check(src.includes('@keyframes dpi-breathe'), 'the breathing keyframes are in the sheet')
    check(src.includes('@keyframes dpi-sway'), 'the tail-sway keyframes are in the sheet')
  }
}

console.log('\npackage.json — an installable DSH plugin:')
{
  const pkg = JSON.parse(read('package.json'))
  check(pkg.name === 'dsh-pet-indesktop', `name is dsh-pet-indesktop (got ${String(pkg.name)})`)
  check(pkg.version === '0.3.0', `version is 0.3.0, the skins release (got ${String(pkg.version)})`)
  check(pkg.type === 'module', 'type is module')
  check(pkg.license === 'BSD-3-Clause', `license is BSD-3-Clause (got ${String(pkg.license)})`)
  check(pkg.author === 'Gjs9178U', `author is Gjs9178U (got ${String(pkg.author)})`)

  // 1. both dsh fields, or the market/loader rejects or ignores the package
  check(pkg.dsh?.bundle?.patch === './cordis.patch.yml', 'dsh.bundle.patch is declared (the profile layer)')
  check(
    Array.isArray(pkg.dsh?.client?.inject) && pkg.dsh.client.inject.length > 0,
    'dsh.client.inject is declared and non-empty (dsh.client alone is rejected by the market)',
  )
  check(pkg.dsh?.client?.platform === 'web', `dsh.client.platform is web (got ${String(pkg.dsh?.client?.platform)})`)

  // 2. no lifecycle scripts: the install must not need a compiler
  const scripts = pkg.scripts ?? {}
  const lifecycle = ['prepare', 'postinstall', 'preinstall', 'install', 'prepublishOnly'].filter((s) => scripts[s] !== undefined)
  check(lifecycle.length === 0, `no lifecycle scripts (found: ${lifecycle.join(', ') || 'none'})`)

  // 3. the peerDependencies rule
  const peers = Object.keys(pkg.peerDependencies ?? {})
  check(
    !peers.some((p) => p.startsWith('@deepseek-ai/')),
    `no @deepseek-ai/* in peerDependencies (DSH >= 0.2.0 silently drops mismatches); peers: ${peers.join(', ') || 'none'}`,
  )
  check(peers.length === 1 && peers[0] === 'react', `the only peer is react (got: ${peers.join(', ') || 'none'})`)
  check(pkg.peerDependenciesMeta?.react?.optional === true, 'react is marked optional in peerDependenciesMeta')

  // 4. there is no compiler and no npm dependency in this package
  check(
    pkg.devDependencies === undefined,
    `no devDependencies — the build is two copies and needs no npm install (found: ${Object.keys(pkg.devDependencies ?? {}).join(', ') || 'none'})`,
  )
  check(
    scripts['build:client'] === undefined,
    'no build:client script — there is no client bundler any more',
  )
  check(scripts.build === 'node scripts/build.mjs', `build runs node scripts/build.mjs (got ${String(scripts.build)})`)
  check(
    scripts['verify:pet'] === 'node scripts/verify-pet.mjs',
    `verify:pet runs the pure-function verifier (got ${String(scripts['verify:pet'])})`,
  )
  check(
    typeof scripts.check === 'string' && scripts.check.includes('verify:pet'),
    'npm run check runs the pet verifier too',
  )

  // 5. `files` must actually carry the plugin
  const files = pkg.files ?? []
  for (const entry of ['lib', 'cordis.patch.yml', 'README.md', 'README.en.md', 'CHANGELOG.md', 'ARCHITECTURE.md', 'LICENSE']) {
    check(files.includes(entry), `files[] includes ${entry}`)
  }

  // 6. exports must point at files that exist
  for (const [sub, value] of Object.entries(pkg.exports ?? {})) {
    const target = typeof value === 'string' ? value : value?.default
    if (target === undefined || target === './package.json') continue
    check(existsSync(join(ROOT, target)), `exports["${sub}"] -> ${target} exists`)
  }
  check(
    existsSync(join(ROOT, pkg.main ?? '')),
    `main points at a real file (${String(pkg.main)})`,
  )
  check(
    existsSync(join(ROOT, pkg.types ?? '')),
    `types points at a real file (${String(pkg.types)})`,
  )
}

console.log('\nthe skins:')
{
  /**
   * The skin files are the feature now, so each one gets the same treatment the
   * bundle does: the shipped copy must equal the source copy, byte for byte, and it
   * must actually be a PNG. The magic-bytes check is what catches a placeholder text
   * file committed under a .png name — a failure that would otherwise only show up
   * as a broken picture in a browser nothing here can open.
   */
  const EXPECTED = ['deepsea', 'sakura', 'mint', 'twilight', 'caramel', 'silver', 'ink', 'ember']
  const sourceIds = readdirSync(fileAt('assets/skins'))
    .filter((name) => name.endsWith('.png'))
    .map((name) => name.slice(0, -4))
    .sort()
  const shippedIds = readdirSync(fileAt('lib/assets/skins'))
    .filter((name) => name.endsWith('.png'))
    .map((name) => name.slice(0, -4))
    .sort()

  check(
    JSON.stringify(sourceIds) === JSON.stringify([...EXPECTED].sort()),
    `assets/skins/ holds exactly the eight known skins (got ${sourceIds.join(', ') || 'nothing'})`,
  )
  check(
    JSON.stringify(shippedIds) === JSON.stringify(sourceIds),
    `lib/assets/skins/ holds exactly what assets/skins/ holds (got ${shippedIds.join(', ') || 'nothing'})`,
  )
  // Nothing may linger directly in lib/assets: the layout moved once, and the file
  // that was left behind was a 200 KB stale copy.
  const flat = readdirSync(fileAt('lib/assets')).filter((name) => name.endsWith('.png'))
  check(flat.length === 0, `lib/assets/ holds no stale flat PNGs (got ${flat.join(', ') || 'none'})`)

  for (const id of sourceIds) {
    const source = readFileSync(fileAt(`assets/skins/${id}.png`))
    const shipped = readFileSync(fileAt(`lib/assets/skins/${id}.png`))
    check(shipped.equals(source), `lib/assets/skins/${id}.png is byte-identical to assets/skins/${id}.png`)
    check(
      shipped.length > 8 && shipped.subarray(0, 8).toString('hex') === '89504e470d0a1a0a',
      `${id}.png starts with the PNG magic bytes (got ${shipped.subarray(0, 8).toString('hex')})`,
    )
    // 8-byte signature + IHDR: width and height sit at fixed offsets.
    const width = shipped.readUInt32BE(16)
    const height = shipped.readUInt32BE(20)
    check(width === 420 && height === 409, `${id}.png is 420x409 (got ${String(width)}x${String(height)})`)
    check(shipped.length > 50 * 1024, `${id}.png is a real image, not a placeholder (${String(shipped.length)} bytes)`)
  }

  // The client's allow-list must match the directory EXACTLY, in both directions:
  // a file with no id is unreachable, and an id with no file is a broken swatch.
  const bundle = read('lib/client.js')
  const idsRaw = /const SKIN_IDS = Object\.freeze\(\[([^\]]+)\]\)/.exec(bundle)?.[1] ?? null
  const clientIds = idsRaw === null ? null : [...idsRaw.matchAll(/'([^']+)'/g)].map((match) => match[1])
  check(clientIds !== null, 'lib/client.js declares a SKIN_IDS allow-list')
  if (clientIds !== null) {
    check(
      JSON.stringify([...clientIds].sort()) === JSON.stringify(sourceIds),
      `the client's skin list matches the directory exactly (client: ${clientIds.join(', ')} | files: ${sourceIds.join(', ')})`,
    )
    check(new Set(clientIds).size === clientIds.length, 'the client skin list has no duplicates')
  }

  const host = read('lib/host/index.js')
  const hostIdsRaw = /const SKIN_IDS = Object\.freeze\(\[([^\]]+)\]\)/.exec(host)?.[1] ?? null
  const hostIds = hostIdsRaw === null ? null : [...hostIdsRaw.matchAll(/'([^']+)'/g)].map((match) => match[1])
  check(
    hostIds !== null && JSON.stringify([...hostIds].sort()) === JSON.stringify(sourceIds),
    `the host's allow-list matches the directory exactly (host: ${String(hostIds?.join(', '))})`,
  )

  // The client's URL prefix and the host's route must describe the same address.
  const clientPrefix = /const SKIN_URL_PREFIX = '([^']+)'/.exec(bundle)?.[1] ?? null
  check(
    clientPrefix === '/dsh-pet-indesktop/assets/skins',
    `the client builds skin URLs under /dsh-pet-indesktop/assets/skins (got ${String(clientPrefix)})`,
  )
  check(
    host.includes(`const SKIN_DIR = 'skins'`) && host.includes(`const ASSET_DIR = 'assets'`),
    'the host serves the same directory the client asks for',
  )
  check(
    /const DEFAULT_SKIN = '([^']+)'/.exec(bundle)?.[1] === /const DEFAULT_SKIN = '([^']+)'/.exec(host)?.[1],
    'the client and the host agree on the default skin',
  )
  // The URL is built from an id, never from a stored or requested string: the img's
  // src must be `skinUrl(resolveSkin(...))`, so an unknown value cannot reach it.
  check(
    /src: skinUrl\(resolveSkin\(props\.skin\)\)/.test(bundle),
    "the <img> src goes through skinUrl(resolveSkin(...)) — never a raw value",
  )
  check(!/src: \s*props\.skin/.test(bundle), 'the <img> src is never the raw skin value')

  // The package must say what it is: a release that changed the looks has to name
  // them in its description, or the market listing describes the old plugin.
  check(/skin/i.test(String(JSON.parse(read('package.json')).description)), 'the package description mentions skins')
}

console.log('\nthe build manifest:')
{
  const manifest = JSON.parse(read('lib/.build-manifest.json'))
  check(Array.isArray(manifest.host) && manifest.host.length > 0, 'the manifest lists the host modules')
  check(
    Array.isArray(manifest.client) && manifest.client.length === 1 && manifest.client[0] === 'client.js',
    `the manifest lists exactly one client artifact (got ${JSON.stringify(manifest.client)})`,
  )
  check(
    Array.isArray(manifest.skins) && manifest.skins.length === 8 && manifest.skins.includes('deepsea'),
    `the manifest lists all eight skins (got ${JSON.stringify(manifest.skins)})`,
  )
  const skinBytes = readdirSync(fileAt('lib/assets/skins')).reduce(
    (total, name) => total + statSync(fileAt(`lib/assets/skins/${name}`)).size,
    0,
  )
  check(
    typeof manifest.skinsBytes === 'number' && manifest.skinsBytes === skinBytes,
    `the manifest records the real total skin size (got ${String(manifest.skinsBytes)}, want ${String(skinBytes)})`,
  )
  check(typeof manifest.builtAt === 'string', 'the manifest records when it was built')
  check(typeof manifest.generator === 'string', 'the manifest records its generator')
  check(
    typeof manifest.clientBundleBytes === 'number' &&
      manifest.clientBundleBytes === statSync(fileAt('lib/client.js')).size,
    'the manifest records the real client artifact size',
  )
}

console.log('')
if (failures.length === 0) {
  console.log('all build checks passed')
  process.exit(0)
}
console.log(`${String(failures.length)} check(s) failed:`)
for (const f of failures) console.log('  - ' + f)
process.exit(1)
