/**
 * build.mjs — the whole build, in Node, with no compiler and no bash.
 *
 * What this package's build actually is:
 *
 *   1. host half   copy src/host/*.js -> lib/host/*.js (plain JS, no compiler,
 *                  relative ESM imports) and write the one-line lib/index.js
 *                  shim that `main` and the `exports` map point at
 *   2. client half  copy src/client/index.js -> lib/client.js, prepending a
 *                  generated banner. Byte-for-byte copy otherwise: there is no
 *                  transform step anywhere in this package, so the shipped
 *                  client is the reviewed source
 *   3. guards       the CSS template literal must be present in both copies and
 *                  identical once whitespace is normalised, and lib/client.js
 *                  must still be in the loader-wrapper shape the web shell can
 *                  evaluate
 *   4. manifest     record exactly what is in lib/, so "is lib/ current?" is
 *                  answerable without guessing
 *
 * Why a copy and not a bundle: the DSH web shell evaluates the client bundle as
 * a SCRIPT with `window.__ModuleLoader__` defined (the sibling plugin
 * dsh-boot-animation ships exactly that envelope), so the artifact has to be
 * plain JavaScript in that wrapper — not ESM, and not TypeScript. Nothing here
 * needs npm, a bundler or a type-checker, and the package installs straight from
 * a git checkout with no prepare/postinstall script, which is what keeps it away
 * from pnpm's allowBuilds gate.
 *
 * Usage: node scripts/build.mjs
 */
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')
const SRC_HOST = join(ROOT, 'src', 'host')
const SRC_CLIENT = join(ROOT, 'src', 'client', 'index.js')
const LIB = join(ROOT, 'lib')
const LIB_HOST = join(LIB, 'host')

/**
 * The generated banner for lib/client.js.
 *
 * It is built from a plain array joined with newlines and contains NO backtick
 * character, so it can never be confused for the CSS template literal by a
 * line-based scan of the built file.
 */
const CLIENT_BANNER = [
  '/**',
  ' * GENERATED FILE — DO NOT EDIT BY HAND.',
  ' *',
  ' * Generated by scripts/build.mjs, which copies src/client/index.js verbatim',
  ' * and prepends this banner. The source of truth is src/client/index.js; an',
  ' * edit made here is overwritten by the next build and will be reported as a',
  ' * drift by scripts/verify-build.mjs and scripts/verify-client-boot.mjs.',
  ' */',
].join('\n')

console.log('=== host half: src/host/*.js -> lib/host/*.js (+ lib/index.js) ===')
if (!existsSync(SRC_HOST)) {
  console.error('build: src/host is missing')
  process.exit(1)
}
mkdirSync(LIB_HOST, { recursive: true })

const sources = readdirSync(SRC_HOST).filter((name) => name.endsWith('.js'))
if (!sources.includes('index.js')) {
  console.error('build: src/host/index.js is missing')
  process.exit(1)
}

// Prune first: a module removed from src must not survive in lib.
let pruned = 0
for (const name of readdirSync(LIB_HOST)) {
  if (!name.endsWith('.js')) continue
  if (sources.includes(name)) continue
  rmSync(join(LIB_HOST, name))
  pruned += 1
}
for (const name of sources) {
  cpSync(join(SRC_HOST, name), join(LIB_HOST, name))
}

/**
 * `lib/index.js` is GENERATED, not copied.
 *
 * The package entry has to sit at `lib/index.js` (that is what `main` and the
 * `exports` map point at), while the host modules live in `lib/host/`. Copying
 * `src/host/index.js` up a level would leave its relative imports pointing at
 * files that are not there — a mistake that only shows up when the plugin is
 * loaded. A one-line re-export cannot have that problem.
 */
const ENTRY = `/**
 * Generated by scripts/build.mjs. Do not edit — edit src/host/index.js.
 *
 * The host half lives in ./host/ so that each collaborator is its own module;
 * this file exists because \`main\` and the \`exports\` map point at lib/index.js,
 * and copying src/host/index.js up a level would leave its relative imports
 * pointing at files that are not there.
 *
 * \`export *\` rather than a hand-written named list, on purpose: this plugin also
 * publishes \`limits\`, \`clampPercent\` and \`validateStatePayload\` for its verifiers,
 * and a list maintained here would silently drop the next export someone adds.
 * The ESM surface is the host module's, with no second place to keep in step.
 */
export * from './host/index.js'
`
writeFileSync(join(LIB, 'index.js'), ENTRY, 'utf8')
console.log(`host: copied ${String(sources.length)} module(s), pruned ${String(pruned)}, wrote lib/index.js shim`)

console.log('=== client half: src/client/index.js -> lib/client.js (copied, banner prepended) ===')
if (!existsSync(SRC_CLIENT)) {
  console.error('build: src/client/index.js is missing — it is the source of truth for the client half')
  process.exit(1)
}
const clientSource = readFileSync(SRC_CLIENT, 'utf8')
const clientBundle = CLIENT_BANNER + '\n' + clientSource
writeFileSync(join(LIB, 'client.js'), clientBundle, 'utf8')
console.log(`client: wrote lib/client.js (${String(Buffer.byteLength(clientBundle))} bytes)`)

/**
 * The wrapper shape is the whole point of the artifact, so the build refuses to
 * write something the loader cannot evaluate. Evaluated as a script, ESM syntax
 * has nowhere to go: no `import`, no `export`, no `window.__ModuleLoader__.load`.
 */
{
  const problems = []
  if (!/window\.__ModuleLoader__\.load\(\{/.test(clientBundle)) {
    problems.push('it does not contain window.__ModuleLoader__.load({')
  }
  if (!/id:\s*['"]dsh-pet-indesktop['"]/.test(clientBundle)) {
    problems.push("it does not declare id: 'dsh-pet-indesktop'")
  }
  if (/^\s*export\s+(?:const|let|var|function|default|\{)/m.test(clientBundle)) {
    problems.push('it contains an ESM export statement (the loader evaluates this file as a script)')
  }
  if (/^\s*import\s[^\n]*from\s*['"]/m.test(clientBundle)) {
    problems.push('it contains a static ESM import (react must come from the loader require)')
  }
  if (problems.length > 0) {
    console.error('build: lib/client.js is not in the loader-wrapper format:')
    for (const problem of problems) console.error('  - ' + problem)
    process.exit(1)
  }
  console.log('  ok   lib/client.js is in the window.__ModuleLoader__ wrapper format (no ESM syntax)')
}

/**
 * The sheet must be present in both copies and agree.
 *
 * After the copy above they are identical BY CONSTRUCTION, which is the point:
 * the guard exists to catch someone editing lib/client.js by hand, or the copy
 * silently breaking. Whitespace is normalised away so the comparison is about
 * the sheet's content, not its indentation.
 */
function sheetOf(text) {
  const match = /const CSS = `([\s\S]*?)`/.exec(text)
  return match === null ? null : match[1].replace(/\r/g, '').replace(/[ \t]+$/gm, '').trim()
}

const srcSheet = sheetOf(clientSource)
const libSheet = sheetOf(clientBundle)
if (srcSheet === null) {
  console.error('build: could not find the CSS template literal in src/client/index.js')
  process.exit(1)
}
if (libSheet === null) {
  console.error('build: could not find the CSS template literal in lib/client.js')
  process.exit(1)
}
if (srcSheet !== libSheet) {
  console.error('build: the shipped stylesheet differs from src/client/index.js.')
  console.error('lib/client.js is a copy of src/client/index.js, so the only way this happens is')
  console.error('an edit made directly in lib/ (or a broken copy). Fix src/client/index.js and re-run')
  console.error('`node scripts/build.mjs` — never edit lib/client.js by hand.')
  process.exit(1)
}
console.log('  ok   CSS sheet identical in src/client/index.js and lib/client.js (whitespace aside)')

// A staleness marker that never changes without a real change.
const manifest = {
  builtAt: new Date().toISOString(),
  generator: 'scripts/build.mjs (host copy + client copy with banner + manifest)',
  host: sources.map((name) => name),
  client: ['client.js'],
  types: ['types/index.d.ts', 'types/client/index.d.ts'],
  clientBundleBytes: Buffer.byteLength(clientBundle),
}
writeFileSync(join(LIB, '.build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8')

console.log('=== Build complete ===')
console.log('')
console.log('The client half WAS rebuilt: lib/client.js is src/client/index.js plus a generated banner.')
console.log('No compiler, no bundler and no npm dependency is involved — the copy is the build.')
console.log('Now: node scripts/verify-build.mjs && node scripts/verify-client-boot.mjs')
